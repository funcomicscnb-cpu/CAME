#!/usr/bin/env python3
"""Create tiny deterministic real-mode smoke data for CAME."""

from __future__ import annotations

import argparse
import csv
import shutil
from pathlib import Path


GENOME_PREFIX = "ACGT" * 300
CHROM = "chrSmoke"
SPECIES = "Smoke_species"
REFERENCE_ID = "smoke_ref"


def wrap_sequence(sequence: str, width: int = 80) -> str:
    return "\n".join(sequence[idx : idx + width] for idx in range(0, len(sequence), width))


def subseq(start_1based: int, length: int) -> str:
    start = start_1based - 1
    return GENOME_PREFIX[start : start + length]


def write_fastq(path: Path, read_id: str, sequence: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    quality = "I" * len(sequence)
    path.write_text(f"@{read_id}\n{sequence}\n+\n{quality}\n")


def write_reference(reference_dir: Path) -> None:
    reference_dir.mkdir(parents=True, exist_ok=True)
    (reference_dir / "smoke.fa").write_text(f">{CHROM}\n{wrap_sequence(GENOME_PREFIX)}\n")
    (reference_dir / "smoke.gtf").write_text(
        "\n".join(
            [
                f'{CHROM}\tCAME\tgene\t101\t260\t.\t+\t.\tgene_id "smoke_gene_1"; gene_name "smoke_gene_1";',
                f'{CHROM}\tCAME\ttranscript\t101\t260\t.\t+\t.\tgene_id "smoke_gene_1"; transcript_id "smoke_tx_1";',
                f'{CHROM}\tCAME\texon\t101\t260\t.\t+\t.\tgene_id "smoke_gene_1"; transcript_id "smoke_tx_1"; exon_number "1";',
                "",
            ]
        )
    )
    (reference_dir / "smoke.chrom.sizes").write_text(f"{CHROM}\t{len(GENOME_PREFIX)}\n")
    (reference_dir / "smoke_regions.bed").write_text(f"{CHROM}\t300\t380\tsmoke_region_1\n")


