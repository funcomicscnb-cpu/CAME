#!/usr/bin/env python3
"""Regression checks for explicit Conda release-lock integrity."""

import importlib.util
from pathlib import Path
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("release_bundle", ROOT / "bin" / "validate_release_bundle.py")
RELEASE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(RELEASE)


class CondaLockTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.path = self.root / "environment" / "conda-linux-64.lock"
        self.path.parent.mkdir()
        self.text = (ROOT / "environment" / self.path.name).read_text()
        self.package = next(line for line in self.text.splitlines() if line.startswith("https://") and "/linux-64/" in line)

    def check_lock(self, text):
        self.path.write_text(text)
        rows = []
        RELEASE.check_conda_lock(rows, self.root)
        self.assertEqual(len(rows), 1)
        return rows[0]

    def test_conda_explicit_export_without_generator_metadata(self):
        text = "\n".join(line for line in self.text.splitlines() if not line.startswith("#"))
        row = self.check_lock("# platform: linux-64\n" + text + "\n")
        self.assertEqual(row["status"], "PASS", row["message"])

    def test_conda_lock_generator_metadata_is_also_accepted(self):
        row = self.check_lock("# Generated by conda-lock.\n# input_hash: " + "a" * 64 + "\n" + self.text)
        self.assertEqual(row["status"], "PASS", row["message"])

    def test_incompatible_checksums_are_rejected(self):
        for checksum in ("A" * 32, "b" * 64, "sha256:" + "b" * 64, "sha256=" + "b" * 64):
            with self.subTest(checksum=checksum):
                replacement = self.package.split("#")[0] + "#" + checksum
                row = self.check_lock(self.text.replace(self.package, replacement))
                self.assertEqual(row["status"], "ERROR")
                self.assertIn("lowercase 32-character MD5", row["message"])

    def test_noarch_first_lock_is_accepted(self):
        lines = self.text.splitlines()
        noarch = next(line for line in lines if line.startswith("https://") and "/noarch/" in line)
        lines.remove(noarch)
        lines.insert(lines.index("@EXPLICIT") + 1, noarch)
        row = self.check_lock("\n".join(lines) + "\n")
        self.assertEqual(row["status"], "PASS", row["message"])

    def test_missing_platform_header(self):
        row = self.check_lock(self.text.replace("# platform: linux-64", ""))
        self.assertEqual(row["status"], "ERROR")
        self.assertIn("missing linux-64 platform marker", row["message"])

    def test_token_path_is_rejected_without_exposing_token(self):
        replacement = self.package.replace("/linux-64/", "/t/private-token/linux-64/")
        row = self.check_lock(self.text.replace(self.package, replacement))
        self.assertEqual(row["status"], "ERROR")
        self.assertIn("auth-token URL segment", row["message"])
        self.assertNotIn("private-token", str(row))

    def test_macos_package_urls(self):
        for platform in ("osx-64", "osx-arm64"):
            with self.subTest(platform=platform):
                replacement = self.package.replace("/linux-64/", "/" + platform + "/")
                row = self.check_lock(self.text.replace(self.package, replacement))
                self.assertEqual(row["status"], "ERROR")
                self.assertIn("macOS package URLs", row["message"])

    def test_omission_comment_is_rejected(self):
        row = self.check_lock(self.text + "# no URL for: omitted-package\n")
        self.assertEqual(row["status"], "ERROR")
        self.assertIn("incomplete explicit export", row["message"])

    def test_invalid_package_artifacts_are_rejected(self):
        replacements = {
            "missing checksum": self.package.split("#")[0],
            "invalid checksum": self.package.split("#")[0] + "#not-a-checksum",
            "wrong platform": self.package.replace("/linux-64/", "/linux-aarch64/"),
            "credentials": self.package.replace("https://", "https://user:secret@"),
            "query credential": self.package.replace("#", "?token=secret#"),
            "non-HTTPS": self.package.replace("https://", "http://"),
            "unpinned spec": "python>=3.10",
        }
        for label, replacement in replacements.items():
            with self.subTest(label=label):
                row = self.check_lock(self.text.replace(self.package, replacement))
                self.assertEqual(row["status"], "ERROR")
                self.assertIn("package URL", row["message"])
                self.assertNotIn("secret", row["message"])

    def test_missing_duplicate_and_misplaced_explicit_markers(self):
        for text in (
            self.text.replace("@EXPLICIT\n", ""),
            self.text + "@EXPLICIT\n",
            self.text.replace("@EXPLICIT\n", "") + "@EXPLICIT\n",
        ):
            with self.subTest(text=text[:30]):
                row = self.check_lock(text)
                self.assertEqual(row["status"], "ERROR")
                self.assertIn("exactly one @EXPLICIT", row["message"])

    def test_empty_lock(self):
        row = self.check_lock("# platform: linux-64\n@EXPLICIT\n")
        self.assertEqual(row["status"], "ERROR")
        self.assertIn("no pinned package artifacts", row["message"])

    def test_missing_required_tool(self):
        text = "\n".join(line for line in self.text.splitlines() if "/nextflow-" not in line)
        row = self.check_lock(text)
        self.assertEqual(row["status"], "ERROR")
        self.assertIn("nextflow", row["message"])

    def test_comment_cannot_substitute_for_required_package(self):
        text = "\n".join(line for line in self.text.splitlines() if "/nextflow-" not in line)
        row = self.check_lock("# /nextflow-is-not-an-artifact\n" + text)
        self.assertEqual(row["status"], "ERROR")
        self.assertIn("nextflow", row["message"])


if __name__ == "__main__":
    unittest.main()
